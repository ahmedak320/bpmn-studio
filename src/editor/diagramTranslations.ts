export function interpolateDiagramTemplate(
  template: string,
  replacements: DiagramTranslateReplacements = {}
): string {
  return template.replace(/{([^}]+)}/g, (token, key: string) =>
    Object.prototype.hasOwnProperty.call(replacements, key) ? String(replacements[key]) : token
  )
}

export function translateDiagramForLanguage(
  language: Lang,
  template: string,
  replacements: DiagramTranslateReplacements = {}
): string {
  const translated =
    language === 'ar' ? (ARABIC_DIAGRAM_TRANSLATIONS[template] ?? template) : template
  return interpolateDiagramTemplate(translated, replacements)
}

/**
 * diagram-js injects this function once, while the function resolves the
 * current language on every call. The modeler therefore survives language
 * changes; `i18n.changed()` only asks its controls to request fresh strings.
 */
export function translateDiagram(
  template: string,
  replacements: DiagramTranslateReplacements = {}
): string {
  return translateDiagramForLanguage(getLang(), template, replacements)
}
